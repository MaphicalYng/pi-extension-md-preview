#!/usr/bin/env node
/**
 * 把 mermaid v11 的自包含产物 vendor 进仓库（vendored）。
 *
 * 预览页通过动态 import('/mermaid.mjs') 加载同源产物（硬契约：页面不发起
 * 外部网络请求，不能走 CDN），服务器在 /mermaid.mjs 路由上提供该文件。
 *
 * 为什么不是直接复制 dist/mermaid.esm.min.mjs：
 *   mermaid 11.x 的 ESM 产物是分包入口（~30KB），还依赖
 *   dist/chunks/mermaid.esm.min/ 下 100+ 个 chunk，单独一个文件无法加载。
 *   因此改用上游自包含单文件 dist/mermaid.min.js（esbuild IIFE，全部内联），
 *   头尾各加一行桥接，包成单文件 ESM：
 *     - 头部把内部命名空间对象挂到 globalThis（IIFE 尾部按全局取回）；
 *     - 尾部 export default globalThis.mermaid（由上游尾行赋值）。
 *   中间部分是上游原样字节，未做任何改写。
 *
 * 用法：npm run vendor:mermaid
 * 来源：node_modules/mermaid/dist/mermaid.min.js
 * 目标：extensions/md-preview/vendor/mermaid.esm.min.mjs（进 git，~3.5MB）
 */
import { readFileSync, mkdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "node_modules", "mermaid", "dist", "mermaid.min.js");
const dst = join(root, "extensions", "md-preview", "vendor", "mermaid.esm.min.mjs");

let code;
try {
	code = readFileSync(src, "utf8");
} catch {
	console.error(`source not found: ${src}\nrun "npm install" first (or download dist/mermaid.min.js manually)`);
	process.exit(1);
}

// 断言上游产物形状：esbuild 命名空间 IIFE + 尾部全局赋值，缺一则包装会失效。
if (!code.startsWith('"use strict";var __esbuild_esm_mermaid_nm;') || !code.includes('globalThis["mermaid"] = globalThis.__esbuild_esm_mermaid_nm["mermaid"].default;')) {
	console.error("unexpected mermaid.min.js shape; adjust scripts/vendor-mermaid.mjs wrapper for this mermaid version");
	process.exit(1);
}

const head =
	"// vendored mermaid (wrapped as single-file ESM) — generated by scripts/vendor-mermaid.mjs, do not edit\n" +
	"var __esbuild_esm_mermaid_nm = (globalThis.__esbuild_esm_mermaid_nm = globalThis.__esbuild_esm_mermaid_nm || {});\n";
const tail = "\nexport default globalThis.mermaid;\n";

mkdirSync(dirname(dst), { recursive: true });
writeFileSync(dst, head + code + tail);
const mb = (statSync(dst).size / 1024 / 1024).toFixed(2);
console.log(`vendored mermaid ESM -> ${dst} (${mb} MB)`);
